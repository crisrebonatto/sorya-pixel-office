// Fonte pixel 3×5 para textos do cenário (letreiro, telas, quadro branco).
// Rótulos legíveis (nomes, balões) usam fonte do sistema em alta resolução.
(function () {
  'use strict';
  const AO = (window.AO = window.AO || {});

  // Cada glifo: 5 linhas de 3 bits (string '1'/'0').
  const G = {
    A: ['010', '101', '111', '101', '101'], B: ['110', '101', '110', '101', '110'],
    C: ['011', '100', '100', '100', '011'], D: ['110', '101', '101', '101', '110'],
    E: ['111', '100', '110', '100', '111'], F: ['111', '100', '110', '100', '100'],
    G: ['011', '100', '101', '101', '011'], H: ['101', '101', '111', '101', '101'],
    I: ['111', '010', '010', '010', '111'], J: ['001', '001', '001', '101', '010'],
    K: ['101', '101', '110', '101', '101'], L: ['100', '100', '100', '100', '111'],
    M: ['101', '111', '111', '101', '101'], N: ['110', '101', '101', '101', '101'],
    O: ['010', '101', '101', '101', '010'], P: ['110', '101', '110', '100', '100'],
    Q: ['010', '101', '101', '110', '011'], R: ['110', '101', '110', '101', '101'],
    S: ['011', '100', '010', '001', '110'], T: ['111', '010', '010', '010', '010'],
    U: ['101', '101', '101', '101', '111'], V: ['101', '101', '101', '101', '010'],
    W: ['101', '101', '111', '111', '101'], X: ['101', '101', '010', '101', '101'],
    Y: ['101', '101', '010', '010', '010'], Z: ['111', '001', '010', '100', '111'],
    0: ['111', '101', '101', '101', '111'], 1: ['010', '110', '010', '010', '111'],
    2: ['110', '001', '010', '100', '111'], 3: ['110', '001', '010', '001', '110'],
    4: ['101', '101', '111', '001', '001'], 5: ['111', '100', '110', '001', '110'],
    6: ['011', '100', '110', '101', '010'], 7: ['111', '001', '010', '010', '010'],
    8: ['010', '101', '010', '101', '010'], 9: ['010', '101', '011', '001', '110'],
    ':': ['000', '010', '000', '010', '000'], '.': ['000', '000', '000', '000', '010'],
    '-': ['000', '000', '111', '000', '000'], '/': ['001', '001', '010', '100', '100'],
    '<': ['001', '010', '100', '010', '001'], '>': ['100', '010', '001', '010', '100'],
    '!': ['010', '010', '010', '000', '010'], '?': ['110', '001', '010', '000', '010'],
    '+': ['000', '010', '111', '010', '000'], '%': ['101', '001', '010', '100', '101'],
    '#': ['101', '111', '101', '111', '101'], '_': ['000', '000', '000', '000', '111'],
    '*': ['000', '101', '010', '101', '000'], '=': ['000', '111', '000', '111', '000'],
    '(': ['010', '100', '100', '100', '010'], ')': ['010', '001', '001', '001', '010'],
    ' ': ['000', '000', '000', '000', '000']
  };

  function text(ctx, str, x, y, color) {
    ctx.fillStyle = color;
    let cx = x;
    for (const ch of String(str).toUpperCase()) {
      const g = G[ch] || G['?'];
      for (let j = 0; j < 5; j++) {
        for (let i = 0; i < 3; i++) {
          if (g[j][i] === '1') ctx.fillRect(cx + i, y + j, 1, 1);
        }
      }
      cx += 4;
    }
    return cx - x - 1;
  }

  function width(str) {
    return String(str).length * 4 - 1;
  }

  AO.font = { text, width };
})();
